import { expect, test } from '@playwright/test'
import { registerUser, fillStudioConditions } from './helpers'

test.use({ video: 'on' })
test('current-batch team picking, nested map, and route continuity', async ({ page }, info) => {
  test.setTimeout(60000)
  await page.route('**/api/v1/maps/config', route => route.fulfill({ json: { enabled: false } }))
  await page.goto('/recommend')
  await registerUser(page, 'team')
  await fillStudioConditions(page, ['湖景', '博物馆', '公园'])
  await page.getByRole('button', { name: '更多功能', exact: true }).click()
  await page.getByRole('button', { name: '发起同行挑选' }).click()
  await page.getByRole('button', { name: '开始推荐', exact: true }).click()
  await expect(page.locator('.spatial-workspace')).toHaveAttribute('data-workspace-phase', 'results')
  await expect(page.getByTestId('destination-card')).toHaveCount(2)
  await page.getByRole('button', { name: /^加入候选：/ }).first().click()
  await page.getByRole('button', { name: /^加入候选：/ }).first().click()
  await page.getByRole('button', { name: '查看对比（2）' }).click()
  await expect(page.getByRole('dialog', { name: '候选对比' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '发起同行计划', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '创建同行计划' })).toBeVisible()
  await page.mouse.click(2, 2)
  await expect(page.getByRole('dialog')).toHaveCount(0)
  const card = page.getByRole('button', { name: /^了解/ }).first()
  await card.click()
  await page.getByRole('button', { name: '查看位置', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '景点位置' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog', { name: '景点位置' })).toHaveCount(0)
  await page.goBack()
  await expect(card).toBeFocused()
  await expect(page.locator('.spatial-workspace')).toHaveAttribute('data-workspace-phase', 'results')
  await page.getByRole('button', { name: '↻ 新查询' }).click()
  await expect(page.locator('.spatial-workspace')).toHaveAttribute('data-workspace-phase', 'query')
  await expect(page.locator('.studio-team-mode')).toContainText('同行挑选中')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(page.locator('.spatial-workspace')).toHaveAttribute('data-workspace-phase', 'results')
  await page.evaluate(() => {
    document.querySelector('.coastal-backdrop')?.setAttribute('data-identity', 'same-background')
    document.querySelector('.shell-header')?.setAttribute('data-identity', 'same-nav')
  })
  for (const [name, path] of [['收藏', 'favorites'], ['历史', 'history'], ['计划中心', 'plans']]) {
    await page.getByRole('navigation', { name: '主导航' }).getByRole('link', { name, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/${path}$`))
    await expect(page.locator('.coastal-backdrop')).toHaveAttribute('data-identity', 'same-background')
    await expect(page.locator('.shell-header')).toHaveAttribute('data-identity', 'same-nav')
    await page.waitForTimeout(550)
    await page.screenshot({ path: info.outputPath(`${path}.png`) })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.goBack()
  await expect(page).toHaveURL(/\/history$/)
})
