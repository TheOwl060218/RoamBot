import { installLegacyAssistantFixture } from './helpers'
import { expect, test } from '@playwright/test'
import { studioResponse } from '../tests/fixtures/studio'
test.beforeEach(async ({ page }) => { await installLegacyAssistantFixture(page) })

test('nested map Back then detail Back restores original card and forward', async ({ page }) => {
  await page.route('**/api/v1/assistant/turns', route => route.fulfill({ json: { revision: 0, reply: '这是地图中的回答', source: 'demo' } }))
  await page.route('**/api/v1/maps/config', route => route.fulfill({ json: { enabled: false } }))
  await page.goto('/recommend')
  await page.evaluate(result => { sessionStorage.removeItem('roambot.studio.session.v1'); sessionStorage.setItem('roambot.session.search-result.v1', JSON.stringify(result)); const state = { ...history.state }; delete state.roambotStudioStageSlot; delete state.roambotStudioStage; delete state.roambotStudioResultSlot; history.replaceState(state, '', location.href) }, studioResponse)
  await page.reload()
  const card = page.getByRole('button', { name: '了解金鸡湖景区' })
  await expect(page.getByTestId('destination-card')).toHaveCount(studioResponse.items.length)
  await card.click()
  await page.getByRole('button', { name: '查看位置', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '景点位置' })).toBeVisible()
  await expect(page.getByRole('button', { name: '打开地图对话' })).toBeVisible()
  await page.getByRole('button', { name: '打开地图对话' }).click()
  await expect(page.getByRole('region', { name: '地图对话', exact: true }).getByRole('textbox', { name: '继续补充条件' })).toBeEditable()
  await page.getByRole('region', { name: '地图对话', exact: true }).getByRole('textbox').fill('看看这个地点')
  await page.getByRole('region', { name: '地图对话', exact: true }).getByRole('button', { name: '发送消息' }).click()
  await expect(page.getByRole('region', { name: '地图对话', exact: true }).getByText('这是地图中的回答')).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog', { name: '景点位置' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '查看位置', exact: true })).toBeFocused()
  await page.goBack()
  await expect(card).toBeFocused()
  await expect(page).toHaveURL(/\/recommend$/)
  await page.goForward()
  await expect(page.getByRole('dialog', { name: '金鸡湖景区详情' })).toBeVisible()
  await page.getByRole('button', { name: '查看位置', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '景点位置' })).toHaveCount(0)
  await expect(page.getByRole('dialog', { name: '金鸡湖景区详情' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(card).toBeFocused()
})
