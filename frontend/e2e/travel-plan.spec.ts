import { expect, test } from '@playwright/test'
import path from 'node:path'
import { fillStudioConditions } from './helpers'

test('guest recommendation becomes an owned plan after explicit rerun, anonymous vote and decision', async ({ page, browser }, testInfo) => {
  await page.goto('/recommend')
  await fillStudioConditions(page, ['湖景','博物馆'])
  await page.getByRole('button', { name: '开始推荐', exact: true }).click()
  await page.getByRole('button', { name: /^加入候选：/ }).nth(0).click()
  await page.getByRole('button', { name: /^加入候选：/ }).nth(0).click()
  await page.getByRole('button', { name: '查看对比（2）' }).click()
  await page.getByRole('button', { name: '发起同行计划', exact: true }).click()
  await page.getByRole('tab', { name: '创建账户', exact: true }).click()
  await page.getByLabel('用户名', { exact: true }).fill(`plan_${Date.now()}_${page.viewportSize()!.width}`)
  await page.getByLabel('密码', { exact: true }).fill('RoamBotDemo123!')
  await page.getByRole('button', { name: '注册并登录', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '登录 RoamBot' })).toHaveCount(0)
  const dialog = page.getByRole('dialog', { name: '创建同行计划' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole('button', { name: '确认创建' })).toHaveCount(0)
  await dialog.getByRole('button', { name: '更新推荐' }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: '查看对比（2）' }).click()
  await page.getByRole('button', { name: '发起同行计划', exact: true }).click()
  await page.getByRole('dialog').getByLabel('计划名称').fill('同行验收计划')
  const people = page.getByRole('dialog').getByLabel('预计同行人数')
  await people.fill('')
  await expect(people).toHaveValue('')
  await people.fill('0')
  await page.getByRole('button', { name: '确认创建' }).click()
  const feedback = page.getByRole('dialog').getByRole('alert')
  await expect(feedback).toHaveText('预计同行人数需为 1–100 的整数。')
  expect(await feedback.evaluate(el => getComputedStyle(el).borderRadius)).toBe('24px')
  await people.fill('2')
  await page.getByRole('button', { name: '确认创建' }).click()
  await expect(page.getByRole('heading', { name: '同行验收计划' })).toBeVisible()
  await expect(page.locator('.primary-nav .plan-status-link')).toBeVisible()
  if (testInfo.project.name.startsWith('mobile')) {
    const mobileState = page.locator('.mobile-plan-anchor .plan-status-detail')
    await expect(mobileState).toBeVisible({ timeout: 1000 })
    await expect(mobileState).toHaveText(/投票中/)
    await expect(mobileState).toBeHidden({ timeout: 7000 })
  }
  await page.getByRole('button', { name: '管理计划', exact: true }).click()
  await page.getByRole('button', { name: '生成邀请', exact: true }).click()
  const invite = await page.getByLabel('邀请链接').inputValue()
  const guestContext = await browser.newContext({ viewport: page.viewportSize()!, reducedMotion: 'reduce' })
  try {
    const guest = await guestContext.newPage()
    await guest.goto(invite)
    await expect(guest.getByRole('heading', { name: '同行验收计划' })).toBeVisible()
    await expect(guest.getByRole('heading', { name: '当前投票结果' })).toHaveCount(0)
    await guest.getByLabel('临时昵称').fill('同行甲')
    await guest.getByRole('button', { name: '加入计划', exact: true }).click()
    await guest.getByRole('button', { name: '去投票', exact: true }).click()
    await guest.getByRole('radio').first().check()
    await guest.getByRole('button', { name: '提交投票', exact: true }).click()
    await expect(guest.getByRole('heading', { name: '当前投票结果' })).toBeVisible()
    await guest.getByRole('button', { name: '修改投票', exact: true }).click()
    await guest.getByRole('radio').nth(1).check()
    await guest.getByRole('button', { name: '保存修改', exact: true }).click()
    await guest.getByRole('button', { name: '修改投票', exact: true }).click()
    await expect(guest.getByRole('radio').nth(1)).toBeChecked()
    await expect(guest.getByRole('alert')).toHaveCount(0)
    await guest.reload()
    await guest.getByRole('button', { name: '修改投票', exact: true }).click()
    await expect(guest.getByRole('button', { name: '保存修改' })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('region', { name: '同行进展' }).getByText('1/2 人已投票', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '检查天气', exact: true }).click()
    await page.getByRole('button', { name: /^查看.*详情$/ }).first().click()
    await expect(page.getByText(/最近检查/).first()).toBeVisible()
    await page.getByRole('button', { name: '去投票', exact: true }).click()
    await page.getByRole('radio').first().check()
    await page.getByRole('button', { name: '提交投票', exact: true }).click()
    await expect(page.getByRole('region', { name: '同行进展' }).getByText('2/2 人已投票', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '结束投票', exact: true }).click()
    await page.getByRole('button', { name: '确认结束投票', exact: true }).click()
    await expect(page.getByText('待决定', { exact: true })).toBeVisible()
    await expect(page.getByRole('radio')).toHaveCount(0)
    await guest.reload()
    await expect(guest.getByText(/等待发起者决定目的地/)).toBeVisible()
    await expect(guest.getByRole('radio')).toHaveCount(0)
    await page.getByRole('button', { name: '重新开放投票', exact: true }).click()
    await page.getByRole('button', { name: '确认重新开放', exact: true }).click()
    await expect(page.getByRole('region', { name: '同行进展' }).getByText('2/2 人已投票', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '结束投票', exact: true }).click()
    await page.getByRole('button', { name: '确认结束投票', exact: true }).click()
    await page.getByRole('button', { name: /^确定苏州博物馆$/ }).click()
    await page.getByRole('button', { name: '确认决定', exact: true }).click()
    await expect(page.getByText('最终目的地', { exact: true })).toBeVisible()
    await guest.reload()
    await expect(guest.getByText(/发起者已确定目的地/)).toBeVisible()
    await expect(guest.getByRole('radio')).toHaveCount(0)
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const transition = await page.locator('.primary-nav .plan-status-link').evaluate(element => getComputedStyle(element).transitionDuration)
    expect(transition).toBe('0s')
    for (const surface of [page, guest]) {
      const overflow = await surface.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
      expect(overflow).toBe(false)
    }
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }))
    await page.screenshot({ path: path.resolve('../docs/competition/evidence', `travel-plan-detail-${testInfo.project.name}.png`),
      fullPage: true, mask: [page.getByLabel('邀请链接')] })
    await guest.screenshot({ path: path.resolve('../docs/competition/evidence', `travel-plan-guest-${testInfo.project.name}.png`), fullPage: true })
    await page.getByRole('link', { name: '计划中心', exact: true }).click()
    await expect(page.getByRole('link', { name: /同行验收计划/ })).toBeVisible()
    await page.screenshot({ path: path.resolve('../docs/competition/evidence', `travel-plan-${testInfo.project.name}.png`), fullPage: true })
    await page.goto('/history')
    await page.getByRole('button', { name: '更多历史操作' }).first().click()
    await page.getByRole('button', { name: '重新查询', exact: true }).click()
    await expect(page).toHaveURL(/\/recommend$/)
    await expect(page.getByRole('region', { name: '当前出行条件' })).toContainText('苏州站')
    await expect(page.getByTestId('destination-card').first()).toBeVisible()
  } finally { await guestContext.close() }
})
