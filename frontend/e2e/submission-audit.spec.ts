  await page.goto('/recommend')
  await fillStudioConditions(page)
  await page.getByRole('button', { name: /编辑目的地范围/ }).click()
  const editor = page.getByRole('dialog', { name: '目的地范围', exact: true })
  await expect(editor).toBeVisible()
