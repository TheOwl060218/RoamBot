  const choices = page.getByRole('dialog', { name: '选择省市', exact: true })
  await expect(choices.getByRole('listbox')).toBeVisible()
  if (focus === 'option') await choices.getByRole('option', { name: '江苏省', exact: true }).focus()
  await page.keyboard.press('Escape')
  await expect(choices).toHaveCount(0)
  await page.screenshot({ path: info.outputPath('region-escape.png') })
  await expect(editor).toBeVisible()
  await expect(editor.getByRole('combobox', { name: '目的地城市范围' })).toBeFocused()
