test('submission audit actual account favorites history and anonymous share', async ({ page, browser }) => {
  await page.goto('/recommend')
  const username = await registerUser(page, 'close')
  await fillStudioConditions(page, ['湖景', '公园'])
  await page.getByRole('button', { name: '开始推荐', exact: true }).click()
  const card = page.getByTestId('destination-card').first()
  await expect(card).toBeVisible()
  const name = (await card.locator('h2').textContent())!.trim()
  await card.getByRole('button', { name: /^了解/ }).click()
  const save = page.getByRole('button', { name: '收藏地点', exact: true })
  await save.click()
  await expect(page.getByRole('button', { name: '取消收藏', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '← 返回地点', exact: true }).click()
  await page.goto('/favorites')
  await expect(page.getByRole('heading', { name: '收藏', exact: true })).toBeVisible()
  await expect(page.getByText(name, { exact: true }).first()).toBeVisible()
  await page.goto('/history')
  await page.getByRole('button', { name: '更多历史操作', exact: true }).first().click()
  const shared = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/share'))
  await page.getByRole('button', { name: '创建分享', exact: true }).click()
  const response = await shared
  expect(response.status()).toBe(201)
  const { share } = await response.json()
  const anonymous = await browser.newContext({ viewport: page.viewportSize()!, reducedMotion: 'reduce' })
  try {
    const guest = await anonymous.newPage()
    await guest.goto(new URL(share.url, page.url()).href)
    await expect(guest.getByRole('heading', { name, exact: true })).toBeVisible()
    await expect(guest.getByText('苏州站', { exact: true })).toHaveCount(0)
    await expect(guest.getByText(username, { exact: true })).toHaveCount(0)
  } finally { await anonymous.close() }
})

test('submission audit actual plan creation invitation anonymous vote and decision', async ({ page, browser }) => {
  test.setTimeout(60000)
  await page.goto('/recommend')
  await registerUser(page, 'plan')
  // Built-in Mock data has lake and museum destinations, but no park candidate.
  await fillStudioConditions(page, ['湖景', '博物馆'])
  await page.getByRole('button', { name: '开始推荐', exact: true }).click()
  await expect(page.getByTestId('destination-card').first()).toBeVisible()
  expect(await page.getByTestId('destination-card').count()).toBeGreaterThanOrEqual(2)
  await page.getByRole('button', { name: /^加入候选：/ }).nth(0).click()
  await page.getByRole('button', { name: /^加入候选：/ }).nth(0).click()
  await page.getByRole('button', { name: '发起同行计划', exact: true }).click()
  const form = page.getByRole('dialog', { name: '创建同行计划' })
  await expect(form).toBeVisible()
  await form.getByLabel('计划名称').fill('提交前合成同行检查')
  await form.getByLabel('预计同行人数').fill('2')
  const creation = page.waitForResponse(r => r.request().method() === 'POST' && /\/api\/v1\/plans$/.test(r.url()))
  await form.getByRole('button', { name: '确认创建', exact: true }).click()
  expect((await creation).status()).toBe(201)
  await expect(page.getByRole('heading', { name: '提交前合成同行检查', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '管理计划', exact: true }).click()
  await page.getByRole('button', { name: '生成邀请', exact: true }).click()
  const invite = await page.getByLabel('邀请链接').inputValue()
  const anonymous = await browser.newContext({ viewport: page.viewportSize()!, reducedMotion: 'reduce' })
  try {
    const guest = await anonymous.newPage()
    await guest.goto(invite)
    await guest.getByLabel('临时昵称').fill('合成同行者')
    await guest.getByRole('button', { name: '加入计划', exact: true }).click()
    await guest.getByRole('button', { name: '去投票', exact: true }).click()
    await guest.getByRole('radio').first().check()
    await guest.getByRole('button', { name: '提交投票', exact: true }).click()
    await expect(guest.getByRole('heading', { name: '当前投票结果', exact: true })).toBeVisible()
    await page.reload()
    await page.getByRole('button', { name: '结束投票', exact: true }).click()
    await page.getByRole('button', { name: '确认结束投票', exact: true }).click()
    await expect(page.getByText('待决定', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: /^确定/ }).first().click()
    await page.getByRole('button', { name: '确认决定', exact: true }).click()
    await expect(page.getByText('已决定', { exact: true }).first()).toBeVisible()
  } finally { await anonymous.close() }
})
